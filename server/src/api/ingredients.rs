use axum::{
    extract::{Path, State},
    http::StatusCode,
    response::IntoResponse,
    routing::{get, post, delete},
    Json, Router,
};
use bigdecimal::BigDecimal;
use serde::{Deserialize, Serialize};
use foodlib_new::auth_context::AuthCtx;
use crate::{api::map_api_error, MyAppState};

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct IngredientsCreateInput {
    pub name: String,
    pub energy: BigDecimal,
    pub comment: String,
    pub group_id: i32,
    // TODO: add more fields for ingredients as needed
}

pub fn ingredients_router() -> Router<MyAppState> {
    Router::new()
    .route("/", get(list_ingredients).post(create_ingredient))
    .route("/{id}", get(get_ingredient))
    .route("/{id}", delete(delete_ingredient))
        .route("/{id}/properties/", get(get_ingredient_properties))
}

async fn list_ingredients(State(state): State<MyAppState>) -> impl IntoResponse {
    let ingredients = state.ingredients().list().await;
    match ingredients {
        Ok(items) => (StatusCode::OK, Json(items)).into_response(),
        Err(err) => map_api_error(err).into_response(),
    }   
}

async fn create_ingredient(
    State(state): State<MyAppState>,
    Json(payload): Json<IngredientsCreateInput>,
) -> impl IntoResponse {
    // TODO: id creation so that it creates a new ingredient with a unique id, or let the database handle it    
    let ingredient = foodlib_new::entities::ingredient::Ingredient {
        id: 0, // Placeholder, should be generated by the database
        name: payload.name,
        energy: payload.energy,
        comment: Option::from(payload.comment),
        group_id: payload.group_id,
    };

    match state.ingredients().create(ingredient).await {
        Ok(item) => (StatusCode::CREATED, Json(item)).into_response(),
        Err(err) => map_api_error(err).into_response(),
    }
}

async fn get_ingredient(
    State(state): State<MyAppState>,
    Path(id): Path<i32>,
) -> impl IntoResponse {
    let ingredient = state.ingredients().get(id).await;
    match ingredient {
        Ok(item) => (StatusCode::OK, Json(item)).into_response(),
        Err(err) => map_api_error(err).into_response(),
    }
}

